/**
 * Inisialisasi Event Listener Modal Capaian & Tujuan Pembelajaran
 */
export function setupLearningTargetModal() {
  const modal = document.getElementById('modal-learning-target');
  if (!modal) return;

  // Bersihkan modal lama di document.body jika ada
  const existingInBody = document.body.querySelectorAll('#modal-learning-target');
  existingInBody.forEach(el => {
    if (el !== modal) el.remove();
  });

  // Pindahkan modal langsung ke <body> agar terlepas dari batas konteks CSS transform di .page-enter
  if (modal.parentElement !== document.body) {
    document.body.appendChild(modal);
  }

  const btnClose = modal.querySelector('#btn-close-modal-target') || document.getElementById('btn-close-modal-target');
  const btnStart = modal.querySelector('#btn-modal-start-learning') || document.getElementById('btn-modal-start-learning');
  const btnOpen  = document.getElementById('btn-open-target-modal');

  function closeModal() {
    modal.classList.add('hidden');
    document.body.classList.remove('overflow-hidden');
  }

  function openModal() {
    modal.classList.remove('hidden');
    document.body.classList.add('overflow-hidden');
  }

  // Auto-open saat halaman dibuka
  openModal();

  if (btnClose) {
    btnClose.addEventListener('click', closeModal);
  }

  if (btnStart) {
    btnStart.addEventListener('click', closeModal);
  }

  // Klik di luar kartu modal (backdrop) untuk menutup
  modal.addEventListener('click', (e) => {
    if (e.target === modal) {
      closeModal();
    }
  });

  // Tombol Escape di keyboard
  const handleKeydown = (e) => {
    if (e.key === 'Escape' && !modal.classList.contains('hidden')) {
      closeModal();
    }
  };
  document.addEventListener('keydown', handleKeydown);

  // Bersihkan modal dari body saat pindah rute/halaman
  window.addEventListener('hashchange', () => {
    document.body.classList.remove('overflow-hidden');
    if (modal && modal.parentElement === document.body) {
      modal.remove();
    }
  }, { once: true });

  // Tombol Re-open di header halaman modul
  if (btnOpen) {
    btnOpen.addEventListener('click', openModal);
  }
}

